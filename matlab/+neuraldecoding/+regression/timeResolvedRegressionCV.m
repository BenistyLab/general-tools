function [accuracy, predictions, foldIndex, metrics] = ...
    timeResolvedRegressionCV(data, labels, k)
%TIMERESOLVEDREGRESSIONCV Time-resolved linear regression with k-fold CV.
%
% Inputs:
%   data   - Numeric tensor of size:
%            sensors x time x trials
%
%   labels - Numeric vector containing one continuous label per trial.
%            Its length must equal the number of trials.
%
%   k      - Number of cross-validation folds.
%
% Outputs:
%   accuracy    - 1 x nTime vector containing cross-validated R^2
%                 at each time point.
%
%   predictions - nTrials x nTime matrix of out-of-fold predictions.
%                 predictions(trial, time) is generated by a model that
%                 was not trained using that trial.
%
%   foldIndex   - nTrials x 1 vector specifying each trial's fold.
%
%   metrics     - Structure containing additional time-resolved metrics:
%                   metrics.R2
%                   metrics.correlation
%                   metrics.RMSE
%                   metrics.MAE
%
% The model at each time point is:
%
%   label = intercept + beta_1*sensor_1 + ... + beta_d*sensor_d
%
% No regularization is applied.

    %% Validate inputs
    if ~isnumeric(data) || ndims(data) ~= 3
        error(['data must be a numeric 3-D tensor with dimensions ' ...
               'sensors x time x trials.']);
    end

    if ~isnumeric(labels) || ~isvector(labels)
        error('labels must be a numeric vector.');
    end

    if ~isscalar(k) || k ~= floor(k) || k < 2
        error('k must be an integer greater than or equal to 2.');
    end

    [nSensors, nTime, nTrials] = size(data);

    labels = labels(:);

    if numel(labels) ~= nTrials
        error(['The number of labels (%d) must equal the number ' ...
               'of trials (%d).'], numel(labels), nTrials);
    end

    if k > nTrials
        error('k cannot be greater than the number of trials.');
    end

    if any(~isfinite(data), 'all')
        error('data contains NaN or Inf values.');
    end

    if any(~isfinite(labels))
        error('labels contains NaN or Inf values.');
    end

    if var(labels) == 0
        error('The labels must contain more than one unique value.');
    end

    %% Create one CV partition shared across all time points
    cv = cvpartition(nTrials, 'KFold', k);

    foldIndex = zeros(nTrials, 1);

    for fold = 1:k
        foldIndex(test(cv, fold)) = fold;
    end

    %% Allocate output
    predictions = nan(nTrials, nTime);

    %% Fit one linear regression model at each time point
    for t = 1:nTime

        % Extract data at the current time point.
        %
        % data(:, t, :) has dimensions:
        % sensors x 1 x trials
        %
        % X will have dimensions:
        % trials x sensors
        X = reshape(data(:, t, :), nSensors, nTrials).';

        for fold = 1:k
            trainTrials = training(cv, fold);
            testTrials  = test(cv, fold);

            XTrain = X(trainTrials, :);
            yTrain = labels(trainTrials);

            XTest = X(testTrials, :);

            % Add a column of ones for the intercept.
            XTrainWithIntercept = [ones(sum(trainTrials), 1), XTrain];
            XTestWithIntercept  = [ones(sum(testTrials), 1), XTest];

            % Ordinary least-squares regression with no regularization.
            beta = XTrainWithIntercept \ yTrain;

            % Generate out-of-fold predictions.
            predictions(testTrials, t) = XTestWithIntercept * beta;
        end
    end

    %% Calculate accuracy metrics at each time point
    R2          = nan(1, nTime);
    correlation = nan(1, nTime);
    RMSE        = nan(1, nTime);
    MAE         = nan(1, nTime);

    % Total variance in the labels, used for cross-validated R^2.
    totalSumSquares = sum((labels - mean(labels)).^2);

    for t = 1:nTime
        predictedLabels = predictions(:, t);
        residuals = labels - predictedLabels;

        residualSumSquares = sum(residuals.^2);

        R2(t) = max(0, 1 - residualSumSquares / totalSumSquares);
        RMSE(t) = sqrt(mean(residuals.^2));
        MAE(t) = mean(abs(residuals));

        % Pearson correlation between observed and predicted labels.
        correlationMatrix = corrcoef(labels, predictedLabels);

        if all(size(correlationMatrix) == [2, 2])
            correlation(t) = correlationMatrix(1, 2);
        end
    end

    accuracy = R2;

    metrics.R2 = R2;
    metrics.correlation = correlation;
    metrics.RMSE = RMSE;
    metrics.MAE = MAE;
end